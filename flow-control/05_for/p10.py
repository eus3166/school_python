"""
글로벌시스템융합과 프로그래밍(1) 실습 문제

실습 10: 누적 곱 계산

숫자의 개수를 입력받고, 그만큼 숫자를 입력받아
모든 숫자의 곱을 구하여 출력하세요.

힌트: 곱셈 누적 변수의 초깃값은 1이어야 합니다.
      for문 안에서 input()을 사용하여 숫자를 입력받습니다.
"""

count = int(input("숫자의 개수를 입력하세요: "))

# 아래에 숫자를 여러 번 입력받아 누적 곱을 구하여 출력하세요

# 누적 변수 선언
total = 1

# count만큼 반복하기
for i in range(1, count + 1):
    # 숫자 입력받기
    num = int(input(f"{i}번째 숫자를 입력하세요: "))

    # 누적 곱하기
    total *= num

# 결과 출력하기
print(f"누적 곱: {total}")