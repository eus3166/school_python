"""
글로벌시스템융합과 프로그래밍(1) 실습 문제

실습 1: 숫자 맞추기 게임

정답(42)을 맞출 때까지 반복해서 입력받습니다.
while + break를 사용합니다.

[조건]
- 정답보다 작으면 "더 큰 수를 입력하세요" 출력
- 정답보다 크면 "더 작은 수를 입력하세요" 출력
- 정답을 맞추면 "정답입니다!" 출력 후 종료
"""

answer = 42

# 아래에 숫자 맞추기 게임을 작성하세요

# 참일 때까지 반복하기
while True:
    # 숫자 입력받기
    num = int(input("숫자를 입력하세요: "))

    # 정답보다 작으면 "더 큰 수를 입력하세요" 출력
    if num < answer:
        print("더 큰 수를 입력하세요")

    # 정답보다 크면 "더 작은 수를 입력하세요" 출력
    elif num > answer:
        print("더 작은 수를 입력하세요")

    # 정답을 맞추면 "정답입니다!" 출력 후 즉시 종료
    else:
        print("정답입니다!")
        break