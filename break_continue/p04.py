"""
글로벌시스템융합과 프로그래밍(1) 실습 문제

실습 4: 음수 입력시 종료

숫자를 계속 입력받다가 음수가 입력되면
지금까지 입력한 양수들의 합계를 출력하고 종료합니다.

[조건]
- while True로 무한 반복
- 음수 입력 시 break로 종료
- 0은 합계에 포함
- 종료 후 합계 출력
"""

total = 0

# 아래에 음수 입력시 종료하는 프로그램을 작성하세요

# 참일 때까지 반복
while True:
    # 입력 받기
    num = int(input("숫자를 입력하세요: "))

    # 음수이면
    if num < 0:
        # 즉시 반복 종료
        break

    # total에 누적
    total += num

# 합계 출력
print(f"합계: {total}")