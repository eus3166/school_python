"""
글로벌시스템융합과 프로그래밍(1) 실습 문제

실습 6: 짝수만 누적

5개의 숫자를 입력받되, 홀수는 건너뛰고 짝수만 합계에 누적합니다.
마지막에 짝수의 합계를 출력합니다.

[조건]
- for 반복문으로 5번 입력받기
- 홀수이면 continue로 건너뛰고 "홀수는 건너뜁니다" 출력
- 짝수이면 합계에 누적
- 마지막에 짝수 합계 출력
"""

total = 0

# 아래에 짝수만 누적하는 코드를 작성하세요

# 5번 반복
for _ in range(5):
    # 입력받기
    num = int(input("숫자를 입력하세요: "))

    # 짝수이면
    if num % 2 == 0:
        # 합계에 누적
        total += num

    # 홀수면
    else:
        # "홀수는 건너뜁니다" 출력
        print("홀수는 건너뜁니다")
        # 건너뛰기
        continue

# 짝수 합계 출력
print(f"짝수 합계: {total}")