"""
글로벌시스템융합과 프로그래밍(1) 실습 문제

실습 7: 간단한 메뉴 시스템

메뉴를 반복 출력하고 사용자가 선택하면 해당 동작을 수행합니다.
"q"를 입력하면 프로그램을 종료합니다.

[조건]
- while True로 메뉴를 반복 출력
- 메뉴: 1.인사 2.날씨 q.종료
- "1" 입력 → "안녕하세요!" 출력
- "2" 입력 → "오늘 날씨가 좋습니다!" 출력
- "q" 입력 → "프로그램을 종료합니다" 출력 후 break
- 그 외 → "잘못된 입력입니다" 출력
"""

# 아래에 메뉴 시스템을 작성하세요

# 참일 때까지 반복
while True:
    # 메뉴 문구 출력
    print("===== 메뉴 =====")
    print("1. 인사")
    print("2. 날씨")
    print("q. 종료")
    print("================")

    # 선택 입력
    user_input = input("선택: ")

    # 1이면 "안녕하세요!" 출력
    if user_input == "1":
        print("안녕하세요!")

    # 2이면 "오늘 날씨가 좋습니다!" 출력
    elif user_input == "2":
        print("오늘 날씨가 좋습니다!")

    # q이면 "프로그램을 종료합니다" 출력 후 즉시 반복 종료
    elif user_input == "q":
        print("프로그램을 종료합니다")
        break

    # 그 외는 "잘못된 입력입니다" 출력
    else:
        print("잘못된 입력입니다")