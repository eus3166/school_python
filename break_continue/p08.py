"""
글로벌시스템융합과 프로그래밍(1) 실습 문제

실습 8: 소수 판별

숫자를 입력받아 소수(prime number)인지 판별합니다.
2부터 하나씩 나누어 보다가 나누어 떨어지면 break합니다.

[조건]
- 2 이상의 정수를 입력받기
- 2부터 (입력값-1)까지 나누어 보기
- 나누어 떨어지면 "소수가 아닙니다" 출력 후 break
- 끝까지 나누어 떨어지지 않으면 "소수입니다" 출력

힌트: 나누어 떨어졌는지 여부를 기록하는 변수를 사용하세요.
"""

num = int(input("2 이상의 정수를 입력하세요: "))

# 아래에 소수 판별 코드를 작성하세요

# 2부터 num까지 반복
for n in range(2, num):
    # 나누어 떨어지면 "소수가 아닙니다" 출력
    if num % n == 0:
        print(f"{num}은(는) 소수가 아닙니다")
        # 즉시 반복 종료
        break
    
# 그 외는 "소수입니다" 출력
else:
    print(f"{num}은(는) 소수입니다")