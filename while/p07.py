"""
글로벌시스템융합과 프로그래밍(1) 실습 문제

실습 7: 최대값 찾기

숫자를 반복해서 입력받고, -1을 입력하면 입력을 멈춘 뒤
입력한 숫자 중 가장 큰 값을 출력하세요. (-1은 포함하지 않습니다)

힌트: 현재까지의 최대값을 저장하는 변수를 사용합니다.
"""

# 아래에 최대값을 찾는 코드를 작성하세요

# 최댓값 누적 변수
max_value = 0

# 참일 때까지 반복
while True:
    # 숫자 입력
    num = int(input("숫자를 입력하세요 (-1=종료): "))

    # num이 -1이면 즉시 반복 종료
    if num == -1:
        break

    # num이 max_value보다 크면 최댓값 변경
    if num > max_value:
        max_value = num

# 최댓값 출력
print(f"최댓값: {max_value}")