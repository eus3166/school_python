"""
글로벌시스템융합과 프로그래밍(1) 실습 문제

실습 8: 동전 모으기

목표 금액을 입력받은 뒤, 동전 금액을 반복해서 입력받아 누적합니다.
누적 금액이 목표 금액 이상이 되면 "목표 달성!"을 출력하고 종료합니다.

힌트: 누적 금액이 목표 금액 미만인 동안 반복합니다.
"""

goal = int(input("목표 금액을 입력하세요: "))

# 아래에 동전을 모으는 코드를 작성하세요
saved = 0

# 참일 때까지 반복
while True:
    # 현재와 목표 상태 출력
    print(f"현재: {saved}원 / 목표: {goal}원")

    # 동전 투입 입력
    coin = int(input("동전 투입: "))

    # 동전 금액 누적
    saved += coin

    # 현재 금액이 목표 금액 이상이면 즉시 반복 종료
    if saved >= goal:
        print(f"현재: {saved}원 / 목표: {goal}원")
        print(f"목표 달성! 총 {saved}원을 모았습니다.")
        break