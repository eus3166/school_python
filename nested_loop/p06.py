"""
글로벌시스템융합과 프로그래밍(1) 실습 문제

실습 6: 사각형 테두리

숫자를 입력받아 N x N 크기의 사각형 테두리를 출력하세요.
테두리(첫 줄, 마지막 줄, 첫 칸, 마지막 칸)는 *로,
안쪽은 공백으로 출력합니다.

힌트: if문으로 테두리인지 안쪽인지 판단하세요.
      첫 줄(i==0), 마지막 줄(i==n-1), 첫 칸(j==0), 마지막 칸(j==n-1)
"""

n = int(input("크기를 입력하세요: "))

# 아래에 사각형 테두리를 출력하세요

# 사각형의 윗변 출력
print("*" * n)

# 사각형의 양옆 테두리 출력
for i in range(n - 2):
    print("*", " " * (n - 4), "*")

# 사각형의 아랫변 출력
print("*" * n)