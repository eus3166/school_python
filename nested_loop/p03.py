"""
글로벌시스템융합과 프로그래밍(1) 실습 문제

실습 3: 구구단 전체 출력

2단부터 9단까지 구구단을 전체 출력하세요.
각 단 사이에 빈 줄을 하나 넣으세요.

힌트: 바깥 for문은 단(2~9), 안쪽 for문은 곱하는 수(1~9)입니다.
"""

# 아래에 구구단 전체를 출력하세요

# 2부터 9까지 반복
for i in range(2, 10):
    # 단 출력
    print(f"--- {i}단 ---")

    # 1부터 9까지 반복
    for j in range(1, 10):
        # 결과 출력
        print(f"{i} x {j} = {i * j}")