"""
글로벌시스템융합과 프로그래밍(1) 실습 문제

실습 8: 역 숫자 피라미드

줄 수를 입력받아 아래와 같은 역 숫자 피라미드를 출력하세요.
첫 줄은 n부터 1까지, 마지막 줄은 1만 출력합니다.

힌트: i번째 줄(1부터 시작)에는 (n-i+1)부터 1까지 숫자를 출력합니다.
      range()를 역순으로 사용해 보세요.
"""

n = int(input("줄 수를 입력하세요: "))

# 아래에 역 숫자 피라미드를 출력하세요

# n 역순 반복
for i in range(n, 0, -1):

    # i 역순 반복
    for j in range(i, 0, -1):
        # j 출력
        print(j, end="")
        
    # 줄바꿈
    print()