"""
글로벌시스템융합과 프로그래밍(1) 실습 문제

실습 9: 다이아몬드

숫자를 입력받아 아래와 같은 다이아몬드를 출력하세요.
위쪽 삼각형과 아래쪽 역삼각형을 합쳐서 만듭니다.

힌트: 위쪽 삼각형(1~n줄)과 아래쪽 역삼각형(n-1~1줄)을
      각각 for문으로 출력하세요.
      각 줄마다 공백 + 별을 출력합니다.
      i번째 줄: 공백 (n-i)개 + 별 (2*i-1)개
"""

n = int(input("크기를 입력하세요: "))

# 아래에 다이아몬드를 출력하세요

# 다이아몬드
# 위쪽 삼각형 출력
for i in range(1, n + 1):
    print(" " * (n - i), end = "")
    print("*" * (2 * i - 1), end = "")
    print(" " * (n - i))

# 아래쪽 역삼각형 출력
for i in range(n - 1, 0, -1):
    print(" " * (n - i), end = "")
    print("*" * (2 * i - 1), end = "")
    print(" " * (n - i))