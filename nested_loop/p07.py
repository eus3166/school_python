"""
글로벌시스템융합과 프로그래밍(1) 실습 문제

실습 7: 알파벳 삼각형

줄 수를 입력받아 아래와 같은 알파벳 삼각형을 출력하세요.

힌트: chr(65)는 'A', chr(66)은 'B', chr(67)은 'C'입니다.
      65 + 0 = 65 → 'A', 65 + 1 = 66 → 'B', ...
"""

n = int(input("줄 수를 입력하세요: "))

# 아래에 알파벳 삼각형을 출력하세요

# 1부터 n까지 반복
for i in range(1, n + 1):
    
    # i 반복
    for j in range(i):
        # 알파벳 출력
        print(chr(65 + j), end="")

    # 줄바꿈
    print()