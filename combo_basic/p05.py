"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 5: 성적 평가

점수(0~100)와 출석률(0~100)을 입력받아 등급과 수료 여부를 출력합니다.

등급 기준 (점수 기준):
- 90점 이상: A
- 80점 이상: B
- 70점 이상: C
- 60점 이상: D
- 60점 미만: F

수료 조건: 등급이 F가 아니고, 출석률이 80% 이상이면 수료
그 외에는 미수료 (사유 함께 출력)

힌트: 먼저 등급을 판별하고, 이후 수료 여부를 판단합니다.
"""

score = int(input("점수를 입력하세요 (0~100): "))
attendance = int(input("출석률을 입력하세요 (0~100): "))

# 아래에 등급 판별 + 수료면 여부를 출력하는 코드를 작성하세요

# 90점 이상이면 A
if score >= 90:
    grade = "A"

# 80점 이상이면 B
elif score >= 80:
    grade = "B"

# 70점 이상이면 C
elif score >= 70:
    grade = "C"

# 60점 이상이면 D
elif score >= 60:
    grade = "D"

# 그 외는 F
else:
    grade = "F"

# 등급 출력
print(f"등급: {grade}")


# 수료 여부 판단
if grade == "F":
    # 성적 미달
    print("미수료 - 성적 미달 (60점 이상 필요)")
elif attendance < 80:
    # 출석률 부족
    print("미수료 - 출석률 부족 (80% 이상 필요)")
else:
    # 성적과 출석률 모두 충족
    print("수료를 축하합니다!")