"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 7: 체질량(BMI) 판정

키(cm), 몸무게(kg), 나이를 입력받아 BMI를 계산하고 판정합니다.

BMI 공식: 몸무게(kg) / (키(m) ** 2)

일반 기준 (20세 이상):
- 18.5 미만: 저체중
- 18.5 이상 ~ 23 미만: 정상
- 23 이상 ~ 25 미만: 과체중
- 25 이상: 비만

청소년 기준 (20세 미만):
- 17 미만: 저체중
- 17 이상 ~ 23 미만: 정상
- 23 이상: 과체중 주의

힌트: 나이로 기준을 먼저 나눈 뒤, BMI 값으로 판정합니다.
"""

height = float(input("키를 입력하세요 (cm): "))
weight = float(input("몸무게를 입력하세요 (kg): "))
age = int(input("나이를 입력하세요: "))

# 아래에 BMI를 계산하고 판정하는 코드를 작성하세요

# BMI 구하기
height_m = height / 100
bmi = weight / (height_m ** 2)
print("BMI:", round(bmi, 2))

# 나이에 따라 다른 기준 적용
# 성인 기준
if age >= 20:
    # 18.5 미만이면 저체중 
    if bmi < 18.5:
        print("판정: 저체중")
    # 18.5 이상 ~ 23 미만이면 정상
    elif bmi < 23:
        print("판정: 정상")
    # 23 이상 ~ 25 미만이면 과체중
    elif bmi < 25:
        print("판정: 과체중")
    # 25 이상이면 비만
    else:
        print("판정: 비만")

# 청소년 기준
else:
    # 17 미만이면 저체중
    if bmi < 17:
        print("판정: 저체중 (청소년 기준)")
    # 17 이상 ~ 23 미만이면 정상
    elif bmi < 23:
        print("판정: 정상 (청소년 기준)")
    # 23 이상이면 과체중 주의
    else:
        print("판정: 과체중 주의 (청소년 기준)")