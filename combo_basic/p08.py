"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 8: 놀이공원 입장료

나이와 단체 여부를 입력받아 입장료를 계산합니다.

기본 입장료:
- 3세 이하: 무료
- 4세 ~ 12세: 15000원
- 13세 ~ 18세: 20000원
- 19세 ~ 64세: 30000원
- 65세 이상: 10000원

단체 할인 (10명 이상): 기본 입장료에서 20% 할인

힌트: 나이별 요금을 먼저 정하고, 단체 여부를 추가 판단합니다.
"""

age = int(input("나이를 입력하세요: "))
group_count = int(input("인원 수를 입력하세요: "))

# 아래에 입장료를 계산하는 코드를 작성하세요

# 나이별 기본 입장료 결정
# 나이가 3세 이하이면 0
if age <= 3:
    price = 0
# 나이가 12세 이하이면 15000
elif age <= 12:
    price = 15000
# 나이가 18세 이하이면 20000
elif age <= 18:
    price = 20000
# 나이가 64세 이하이면 30000
elif age <= 64:
    price = 30000
# 그 외는 10000
else:
    price = 10000

# 기본 입장료 출력
print(f"기본 입장료: {price}원")

