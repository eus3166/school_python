"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 6: 전기 요금 계산

전기 사용량(kWh)을 입력받아 누진제를 적용한 요금을 계산합니다.

요금 기준 (누진제):
- 100kWh 이하: kWh당 60원
- 101~200kWh: 처음 100kWh는 60원, 초과분은 kWh당 120원
- 200kWh 초과: 처음 100kWh는 60원, 다음 100kWh는 120원, 나머지는 kWh당 190원

부가세: 요금의 10%를 추가합니다.

힌트: 구간별로 나눠서 계산한 뒤 합산합니다.
"""

usage = int(input("전기 사용량을 입력하세요 (kWh): "))

# 아래에 전기 요금을 계산하는 코드를 작성하세요

# 누진제 구간별 요금 계산
# 100kWh 이하이면 1kWh당 60원
if usage <= 100:
    charge = usage * 60

# 101 ~ 200kWh이면 초과 사용량은 1kWh당 120원
elif usage <= 200:
    charge = 100 * 60 + (usage - 100) * 120

# 200kWh 초과이면 초과 사용량은 1kWh당 190원
else:
    charge = 100 * 60 + 100 * 120 + (usage - 200) * 190

# 전기 요금 출력
print(f"전기 요금: {charge}원")

# 부가세 10% 추가
tax = int(charge * 0.1)
print(f"부가세 (10%): {tax}원")

# 총 납부 금액
total = charge + tax
print(f"총 납부 금액: {total}원")