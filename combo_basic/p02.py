"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 2: 미니 성적 관리

5명의 점수를 입력받아 평균과 최고점을 출력하세요.

[조건]
- 리스트를 사용하지 않고 변수만으로 해결합니다.
- 합계와 최고점을 누적하며 계산합니다.

힌트: for + if + 누적 변수를 사용합니다.
"""

total = 0
best = 0

# 아래에 5명의 점수를 입력받아 평균과 최고점을 출력하세요

# 5번 반복
for i in range(1, 6):
    # 학생 점수 입력
    score = int(input(str(i) + "번 학생 점수: "))

    # 합계에 누적
    total += score

    # 현재 입력된 점수가 최고점보다 크면 갱신
    if score > best:
        best = score

# 평균 구하기
average = total / 5

# 결과 출력
print("평균:", average)
print("최고점:", best)