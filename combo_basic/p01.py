"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 1: 메뉴 주문 시스템

메뉴를 선택하면 금액이 누적되고, 0을 입력하면 총 금액을 출력합니다.

[메뉴]
1. 아메리카노 - 4000원
2. 카페라떼 - 4500원
3. 녹차 - 3500원
0. 주문 완료

힌트: while + if/elif를 사용합니다.
"""

total = 0

# 아래에 메뉴 주문 시스템을 작성하세요

# 0을 입력할 때까지 반복
while True:
    # 매 반복마다 메뉴판 출력
    print("--- 메뉴 ---")
    print("1. 아메리카노 (4000원)")
    print("2. 카페라떼 (4500원)")
    print("3. 녹차 (3500원)")
    print("0. 주문 완료")

    # 메뉴 입력
    choice = int(input("메뉴를 선택하세요: "))

    # 선택한 메뉴에 따라 금액 누적
    if choice == 1:
        total += 4000
        print("아메리카노를 추가했습니다.")

    elif choice == 2:
        total += 4500
        print("카페라떼를 추가했습니다.")

    elif choice == 3:
        total += 3500
        print("녹차를 추가했습니다.")

    # 0 입력 시 즉시 반복 종료
    elif choice == 0:
        break 

# 결과 출력
print(f"총 주문 금액: {total}원")