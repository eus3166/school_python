"""
글로벌시스템융합과 프로그래밍(1) 실습 문제
실습 3: 계절별 인사

월(1~12)을 입력받아 계절을 판별하고, 계절에 맞는 인사말을 출력합니다.

- 3, 4, 5월: 봄 → "따뜻한 봄이에요! 꽃구경 가세요 🌸"
- 6, 7, 8월: 여름 → "더운 여름이에요! 시원하게 보내세요 🌊"
- 9, 10, 11월: 가을 → "선선한 가을이에요! 단풍 구경 가세요 🍂"
- 12, 1, 2월: 겨울 → "추운 겨울이에요! 따뜻하게 입으세요 ⛄"
- 그 외: "잘못된 입력입니다."

힌트: if/elif와 or 연산자를 사용합니다.
"""

month = int(input("월을 입력하세요 (1~12): "))

# 아래에 계절별 인사말을 출력하는 코드를 작성하세요


# 3월부터 5월까지 봄 인사말 출력
if 3 <= month <= 5:
    print("봄입니다.")
    print("따뜻한 봄이에요! 꽃구경 가세요 🌸")

# 6월부터 8월까지 여름 인사말 출력
elif 6 <= month <= 8:
    print("여름입니다.")
    print("더운 여름이에요! 시원하게 보내세요 🌊")

# 9월부터 11월까지 가을 인사말 출력
elif 9 <= month <= 11:
    print("가을입니다.")
    print("선선한 가을이에요! 단풍 구경 가세요 🍂")

# 12월부터 2월까지 겨울 인사말 출력
elif month == 12 or  1 <= month <= 2:
    print("겨울입니다.")
    print("추운 겨울이에요! 따뜻하게 입으세요 ⛄")

# 그 외는 "잘못된 입력입니다." 출력
else:
    print("잘못된 입력입니다.")